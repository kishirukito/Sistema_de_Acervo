BEGIN;

-- Catálogo de autores
CREATE TABLE IF NOT EXISTS public.autores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL UNIQUE
);

-- Catálogo de editoriales
CREATE TABLE IF NOT EXISTS public.editoriales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

-- Relación muchos-a-muchos: libros y autores
CREATE TABLE IF NOT EXISTS public.libro_autores (
    libro_id UUID NOT NULL
        REFERENCES public.libros(id) ON DELETE CASCADE,
    autor_id BIGINT NOT NULL
        REFERENCES public.autores(id) ON DELETE RESTRICT,
    orden SMALLINT NOT NULL CHECK (orden > 0),
    PRIMARY KEY (libro_id, autor_id),
    UNIQUE (libro_id, orden)
);

-- Enlace de libros con editoriales
ALTER TABLE public.libros
    ADD COLUMN IF NOT EXISTS editorial_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'libros_editorial_id_fkey'
          AND conrelid = 'public.libros'::regclass
    ) THEN
        ALTER TABLE public.libros
            ADD CONSTRAINT libros_editorial_id_fkey
            FOREIGN KEY (editorial_id)
            REFERENCES public.editoriales(id)
            ON DELETE RESTRICT;
    END IF;
END
$$;

-- Copiar editoriales existentes
INSERT INTO public.editoriales (nombre)
SELECT DISTINCT btrim(l.editorial)
FROM public.libros AS l
WHERE l.editorial IS NOT NULL
  AND btrim(l.editorial) <> ''
ON CONFLICT (nombre) DO NOTHING;

-- Copiar autores existentes, separando por coma
INSERT INTO public.autores (nombre)
SELECT DISTINCT btrim(x.nombre)
FROM public.libros AS l
CROSS JOIN LATERAL regexp_split_to_table(
    l.autor,
    '\s*,\s*'
) AS x(nombre)
WHERE btrim(x.nombre) <> ''
ON CONFLICT (nombre) DO NOTHING;

-- Relacionar los libros con sus autores, respetando el orden
INSERT INTO public.libro_autores (libro_id, autor_id, orden)
SELECT
    l.id,
    a.id,
    x.orden::SMALLINT
FROM public.libros AS l
CROSS JOIN LATERAL regexp_split_to_table(
    l.autor,
    '\s*,\s*'
) WITH ORDINALITY AS x(nombre, orden)
JOIN public.autores AS a
    ON a.nombre = btrim(x.nombre)
WHERE btrim(x.nombre) <> ''
ON CONFLICT DO NOTHING;

-- Asociar cada libro con su editorial
UPDATE public.libros AS l
SET editorial_id = e.id
FROM public.editoriales AS e
WHERE l.editorial IS NOT NULL
  AND btrim(l.editorial) = e.nombre
  AND l.editorial_id IS DISTINCT FROM e.id;

-- Índices para las consultas y relaciones
CREATE INDEX IF NOT EXISTS idx_libros_editorial_id
    ON public.libros(editorial_id);

CREATE INDEX IF NOT EXISTS idx_libro_autores_autor_id
    ON public.libro_autores(autor_id);

-- El catálogo queda disponible para lectura pública,
-- igual que las tablas de catálogo actuales.
ALTER TABLE public.autores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.editoriales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.libro_autores ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.autores, public.editoriales, public.libro_autores
    TO anon, authenticated;

DROP POLICY IF EXISTS "Lectura pública de autores" ON public.autores;
CREATE POLICY "Lectura pública de autores"
    ON public.autores
    FOR SELECT TO anon, authenticated
    USING (true);

DROP POLICY IF EXISTS "Lectura pública de editoriales" ON public.editoriales;
CREATE POLICY "Lectura pública de editoriales"
    ON public.editoriales
    FOR SELECT TO anon, authenticated
    USING (true);

DROP POLICY IF EXISTS "Lectura pública de libro_autores" ON public.libro_autores;
CREATE POLICY "Lectura pública de libro_autores"
    ON public.libro_autores
    FOR SELECT TO anon, authenticated
    USING (true);

COMMIT;